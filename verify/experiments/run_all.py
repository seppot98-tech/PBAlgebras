"""Compute the critical constants of the catalogue and emit the paper's table.

Outputs
-------
verify/results/constants.json   machine-readable results
paper/generated/constants.tex   the table that the paper \\input{}s

Usage
-----
    python experiments/run_all.py            # default effort
    python experiments/run_all.py --quick    # fast, for CI
    python experiments/run_all.py --full     # slow, for a real run
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pbalg.algebras import CATALOGUE, Algebra  # noqa: E402
from pbalg.search import critical_constants  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "verify" / "results"
GENERATED = ROOT / "paper" / "generated"

#: Which algebras to run at which effort level.  The larger ones are slow
#: because every ratio evaluation maximises a gauge.
QUICK = ["R^2", "C", "H", "M2(R)", "T2(R)", "R[eps]/(eps^2)"]
DEFAULT = QUICK + ["R^3", "M3(R)", "T3(R)", "H(+)R^2"]
#: The block-triangular algebras are the evidence base for the semisimplicity
#: conjecture, so the full run includes them.
FULL = DEFAULT + ["M2(R)(+)M2(R)", "P(1,2)", "P(2,1)"]

LATEX_NAMES = {
    "R": r"$\RR$",
    "R^2": r"$\RR^2$",
    "R^3": r"$\RR^3$",
    "C": r"$\CC$",
    "H": r"$\HH$",
    "M2(R)": r"$M_2(\RR)$",
    "M3(R)": r"$M_3(\RR)$",
    "T2(R)": r"$T_2(\RR)$",
    "T3(R)": r"$T_3(\RR)$",
    "R[eps]/(eps^2)": r"$\RR[\varepsilon]/(\varepsilon^2)$",
    "M2(R)(+)M2(R)": r"$M_2(\RR)\times M_2(\RR)$",
    "H(+)R^2": r"$\HH\times\RR^2$",
    "P(1,2)": r"$P_{1,2}(\RR)$",
    "P(2,1)": r"$P_{2,1}(\RR)$",
}


def fmt(x: float) -> str:
    return r"$\infty$" if not np.isfinite(x) else f"{x:.4f}"


def budget(tries: int, alg: Algebra) -> int:
    """Scale the number of restarts down with the dimension.

    Every ratio evaluation maximises a gauge, so cost grows sharply with
    dim(A); without this a single six-dimensional algebra dominates the run.
    """
    if alg.dim <= 4:
        return tries
    if alg.dim <= 6:
        return max(4, tries // 3)
    return max(3, tries // 6)


def run(names: list[str], tries: int, seed: int, on_row=None) -> list[dict]:
    rows = []
    for name in names:
        alg: Algebra = CATALOGUE[name]()
        t0 = time.time()
        res = critical_constants(alg, gauge="D1", tries=budget(tries, alg),
                                 seed=seed)
        elapsed = time.time() - t0
        print(f"  {res.summary()}   [{elapsed:.1f}s]", flush=True)
        rows.append({
            "algebra": name,
            "dim": alg.dim,
            "kappa": res.kappa,
            "lambda": res.lam,
            "constant": res.constant,
            "is_pb": res.is_pb,
            "seconds": elapsed,
            "witness_kappa": (None if res.kappa_witness is None
                              else np.round(res.kappa_witness, 6).tolist()),
            "witness_lambda": (None if res.lam_witness is None
                               else np.round(res.lam_witness, 6).tolist()),
        })
        if on_row is not None:
            on_row(rows)  # checkpoint, so a long run survives interruption
    return rows


def write_latex(rows: list[dict], path: Path) -> None:
    lines = [
        "% Generated by verify/experiments/run_all.py -- do not edit by hand.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\caption{Critical constants for the gauge $\gauge_1$, found by the",
        r"search described in \S\ref{sec:status}.  Each value is a lower bound",
        r"for a supremum: \statusnum, not \statusproved.  A dash means the",
        r"defect is identically zero; $\infty$ means a nonzero defect with no",
        r"budget, so the algebra is not a PB-algebra for any constant.}",
        r"\label{tab:constants}",
        r"\begin{tabular}{lccc}",
        r"\toprule",
        r"Algebra & $\kap_{\gauge_1}$ & $\lam_{\gauge_1}$ & $C_{\gauge_1}$ \\",
        r"\midrule",
    ]
    for r in rows:
        name = LATEX_NAMES.get(r["algebra"], r["algebra"])
        k = "---" if r["kappa"] == 0 else fmt(r["kappa"])
        l = "---" if r["lambda"] == 0 else fmt(r["lambda"])
        c = fmt(r["constant"]) if r["is_pb"] else r"$\infty$"
        lines.append(f"{name} & {k} & {l} & {c} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    path.write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="CI-sized run")
    ap.add_argument("--full", action="store_true", help="everything, slowly")
    ap.add_argument("--only", nargs="+", metavar="NAME",
                    help="run just these algebras and merge into existing results")
    ap.add_argument("--tries", type=int, default=None, help="override the restart budget")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    if args.only:
        unknown = [n for n in args.only if n not in CATALOGUE]
        if unknown:
            ap.error(f"unknown algebra(s): {', '.join(unknown)}; "
                     f"available: {', '.join(CATALOGUE)}")
        names, tries = args.only, 20
    elif args.quick:
        names, tries = QUICK, 8
    elif args.full:
        names, tries = FULL, 40
    else:
        names, tries = DEFAULT, 20
    if args.tries is not None:
        tries = args.tries

    print(f"critical constants, gauge D1, tries={tries}")
    RESULTS.mkdir(parents=True, exist_ok=True)
    GENERATED.mkdir(parents=True, exist_ok=True)
    path = RESULTS / "constants.json"

    #: Existing rows to merge with, so --only tops up a previous run instead of
    #: discarding it.  Ordering follows the catalogue, not the order of runs.
    previous: list[dict] = []
    if args.only and path.exists():
        previous = [r for r in json.loads(path.read_text())
                    if r["algebra"] not in set(names)]

    order = list(CATALOGUE)

    def merge(rows: list[dict]) -> list[dict]:
        merged = previous + rows
        return sorted(merged, key=lambda r: order.index(r["algebra"])
                      if r["algebra"] in order else len(order))

    def checkpoint(rows: list[dict]) -> None:
        out = merge(rows)
        path.write_text(json.dumps(out, indent=2))
        write_latex(out, GENERATED / "constants.tex")

    rows = run(names, tries, args.seed, on_row=checkpoint)
    checkpoint(rows)
    print(f"\nwrote {RESULTS/'constants.json'}")
    print(f"wrote {GENERATED/'constants.tex'}")


if __name__ == "__main__":
    main()
